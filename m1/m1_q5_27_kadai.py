list_fruits = ['マンゴー', 'パイナップル', 'バンシルー']
fruit = list_fruits.pop(0)  # マンゴーを取出す。マンゴーはリストの0番目なのでpop(0)を使用。親戚がマンゴーを作っていてとても甘いので好きです。
print(f"好きな果物：{fruit}")  # 取り出した果物を出力
print(f"残りのリスト：{list_fruits}")  # 残りのリストを出力

