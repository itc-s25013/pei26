a = 12
b = 5
print(b - a) #5-12 = -7
print(b - abs(2 * b - a) * 3) #5 - 2 * 3
print("{0:05b}".format(b)) # 変数bの値を5桁の2進数で、余った桁は0で埋める
# {0:...}フォーマット対象。最初の0はformat()に渡した最初の引数(b)を指す
# 05 全体の幅を5桁にし、足りない部分を0で埋める
# 2進数(binary)として表示する指定

c = [2, 7, 15, 12, 9]
c.sort() #リストcを昇順に並べ替える
print(c) # [2, 7, 9, 12, 15] 昇順に並べ替えられたリストcを表示
print(c[2:3])
print(f'{(a - b) / c[3]:->8.3f}') 


