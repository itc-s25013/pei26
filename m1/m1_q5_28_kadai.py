days = ['月','月','火','水','木','金','金']    
days.remove('月') #removeメゾットを使って、月をリストから消す
days.remove('金') #removeメゾットを使って、金をリストから消す
days.insert(0, '日') #insertメゾットを使って土をリストの0番目に追加する
days.insert(6, '土') #insertメゾットを使って日をリストの6番目に追加する         
print(days)

